// Builds the Cloudflare Pages upload for each site: dist/<slug>/public (the site + _headers, _redirects,
// _routes.json, 404.html) and dist/<slug>/functions/api/indexnow.js. Deploy with wrangler from dist/<slug>.
// vercel.json is translated, not copied: it stays in sites/ (with api/) as the rollback path to Vercel.
// Usage: node tools/cf-build.mjs [slug ...]   (default: every live site in sites.json + hub)
// Exits non-zero on a missing site folder, an unknown vercel.json pattern, or a leftover Vercel Analytics tag.
import { readFileSync, writeFileSync, existsSync, mkdirSync, rmSync, cpSync, readdirSync, statSync } from "node:fs";
import { join, dirname, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const live = JSON.parse(readFileSync(join(root, "sites.json"), "utf8")).filter(s => s.live !== false).map(s => s.slug).concat("hub");
const slugs = process.argv.length > 2 ? process.argv.slice(2) : live;
const walk = d => readdirSync(d).flatMap(n => { const p = join(d, n); return statSync(p).isDirectory() ? walk(p) : [p]; });
const fail = msg => { throw new Error(msg); };

// What Vercel serves from sites/<slug> but Cloudflare must not: functions, config, test files, junk.
const skip = rel => /^(api|vercel\.json|node_modules)$/.test(rel.split("/")[0]) || /(^|\/)(tests?|__tests__)(\/|$)|\.(test|spec)\.[cm]?js$|(^|\/)\.DS_Store$/.test(rel);

// vercel.json "source" -> Cloudflare _headers globs. Only the patterns the sites use are accepted:
// /(.*), /api/(.*), /vendor/(.*), /(.*)\.(ext|ext), and a literal path like /sw.js. Anything else throws.
const globs = src => {
  const m = src.match(/^((?:\/[\w.-]+)*)\/\(\.\*\)(?:\\\.\(([a-z0-9]+(?:\|[a-z0-9]+)*)\))?$/);
  if (m) return m[2] ? m[2].split("|").map(ext => `${m[1]}/*.${ext}`) : [`${m[1]}/*`]; // _headers has no alternation: one rule per extension
  if (/^(\/[\w.-]+)+$/.test(src)) return [src];
  return fail(`unknown vercel.json header source: ${src}`);
};

// Vercel lets a later rule override an earlier one for the same header; Cloudflare COMBINES values of all matching
// rules ("a, b"). So whenever an earlier rule already set a header, the later rule first detaches it (`! Name`).
const headersFile = vj => {
  const set = new Set(), out = [];
  for (const { source, headers } of vj.headers || []) {
    for (const g of globs(source)) {
      out.push(g);
      for (const { key, value } of headers) { if (set.has(key.toLowerCase())) out.push(`  ! ${key}`); out.push(`  ${key}: ${value}`); }
    }
    headers.forEach(h => set.add(h.key.toLowerCase()));
  }
  // Keep the *.pages.dev copies (project alias and per-deployment hosts) out of search engines.
  out.push("https://:project.pages.dev/*", "  X-Robots-Tag: noindex", "https://:version.:project.pages.dev/*", "  X-Robots-Tag: noindex");
  return "# Generated by tools/cf-build.mjs from vercel.json. Do not edit.\n" + out.join("\n") + "\n";
};

// Path redirects only. The host redirect ("missing": host -> canonical domain) is skipped: the custom domain and
// pages.dev are handled by DNS/noindex. permanent:true -> 301; permanent:false (Vercel 307) -> 307, not 301.
const redirectsFile = vj => "# Generated by tools/cf-build.mjs from vercel.json. Do not edit.\n" + (vj.redirects || []).flatMap(r => {
  if (r.missing) { if (r.missing.length === 1 && r.missing[0].type === "host") return []; fail(`unknown redirect condition: ${JSON.stringify(r.missing)}`); }
  if (!/^\/[\w./-]*$/.test(r.source) || !/^\/[\w./-]*$/.test(r.destination)) fail(`unsupported redirect ${r.source} -> ${r.destination}`);
  return [`${r.source} ${r.destination} ${r.permanent ? 301 : 307}\n`];
}).join("");

// Without a 404.html Cloudflare Pages treats the site as a single-page app and answers every unknown URL with
// index.html and status 200. Vercel returned a real 404, so ship a plain noindex 404 page.
const notFound = `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Page not found</title><meta name="robots" content="noindex">
<style>body{font:18px/1.5 system-ui,sans-serif;max-width:32rem;margin:20vh auto;padding:0 1rem;color:#222;background:#fff}@media(prefers-color-scheme:dark){body{color:#eee;background:#111}a{color:#8ab4ff}}</style>
</head><body><h1>Page not found</h1><p>That page does not exist. <a href="/">Go to the home page</a>.</p></body></html>
`;

for (const slug of slugs) {
  const src = join(root, "sites", slug), out = join(root, "dist", slug), pub = join(out, "public");
  if (!existsSync(join(src, "index.html"))) fail(`site folder missing or not built: sites/${slug}`);
  const vj = JSON.parse(readFileSync(join(src, "vercel.json"), "utf8"));
  rmSync(out, { recursive: true, force: true });
  cpSync(src, pub, { recursive: true, filter: p => !skip(relative(src, p).split(sep).join("/")) });
  writeFileSync(join(pub, "_headers"), headersFile(vj));
  writeFileSync(join(pub, "_redirects"), redirectsFile(vj));
  writeFileSync(join(pub, "_routes.json"), JSON.stringify({ version: 1, include: ["/api/*"], exclude: [] }) + "\n"); // only /api/* runs the Function
  if (!existsSync(join(pub, "404.html"))) writeFileSync(join(pub, "404.html"), notFound);
  mkdirSync(join(out, "functions/api"), { recursive: true });
  cpSync(join(root, "kit/functions/api/indexnow.js"), join(out, "functions/api/indexnow.js"));
  const bad = walk(pub).filter(f => f.endsWith(".html") && readFileSync(f, "utf8").includes("_vercel/insights"));
  if (bad.length) fail(`${slug}: ${bad.length} built page(s) still contain _vercel/insights, e.g. ${relative(root, bad[0])}`);
  console.log(`${slug}: dist/${slug}/public (${walk(pub).length} files)`);
}
